-- Minimal Supabase Storage fixture to test RLS without creating a billable branch.
CREATE SCHEMA storage;
CREATE TABLE storage.buckets(
 id text PRIMARY KEY,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]
);
CREATE TABLE storage.objects(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bucket_id text NOT NULL REFERENCES storage.buckets(id),
 name text NOT NULL
);
CREATE FUNCTION storage.foldername(text) RETURNS text[] LANGUAGE sql IMMUTABLE AS $fn$
 SELECT regexp_split_to_array(regexp_replace($1,'/[^/]+$',''),'/')
$fn$;
